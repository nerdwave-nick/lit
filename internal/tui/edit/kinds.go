package edit

import (
	"context"

	"github.com/nerdwave-nick/nerdwave-workflows/internal/litclient"
	"github.com/nerdwave-nick/nerdwave-workflows/internal/protocol"
	"github.com/nerdwave-nick/nerdwave-workflows/internal/tui/drafts"
)

// Kind is how the editor reads and applies the drafts of one draft kind.
// The editor knows issue bodies; other kinds are registered (Register) by
// the package that owns them, for example internal/tui/comments. What a
// kind declares about owners, new records and claims is in drafts.Kind.
type Kind struct {
	// Read reads d's record now. For a kind whose record exists it fails
	// (typically not_found) when the record is gone; for a new record
	// (drafts.Kind.New) it reports whether a record with the draft's ID has
	// been created already, and Exists false is not an error.
	Read func(ctx context.Context, s *litclient.Session, d drafts.Draft) (Record, error)
	// Request is the transaction that applies content as d's record: an
	// update fenced at d.Revision, or for a new record its creation (with
	// d.RecordID as the new record's ID, so it is created at most once).
	Request func(d drafts.Draft, content string) protocol.PrepareRequest
}

// Record is a draft's record as read now.
type Record struct {
	// Exists is false only for a new record that has not been created.
	Exists bool
	// Title names the record, or the owning issue for comment kinds; ""
	// keeps the draft's title.
	Title    string
	Revision int64
	// Content is the record's editable Markdown content.
	Content string
	// Issue is the issue read for an issue body draft.
	Issue *protocol.Issue
}

// Target names what a draft to start edits.
type Target struct {
	Kind    drafts.Kind
	Project string
	// Record is the edited record. For a new record it is empty (Open
	// generates a draft ID) or a draft ID generated by drafts.NewID.
	Record string
	// Issue owns the record (the record itself for an issue body); for
	// claiming kinds it is the issue claimed on edit. Empty for kinds
	// without an owner.
	Issue string
	// Title names the draft until the record's read gives one.
	Title string
}

// TargetOf is the target a draft edits.
func TargetOf(d drafts.Draft) Target {
	return Target{Kind: d.Kind, Project: d.ProjectID, Record: d.RecordID, Issue: d.IssueID, Title: d.Title}
}

func (t Target) key() string { return string(t.Kind) + "-" + t.Record }

// Register makes the editor edit drafts of kind k through kind; it replaces
// an earlier registration. Register before the editor is used.
func (e *Editor) Register(k drafts.Kind, kind Kind) {
	e.mu.Lock()
	defer e.mu.Unlock()
	e.kinds[k] = kind
}

func (e *Editor) kind(k drafts.Kind) (Kind, error) {
	e.mu.Lock()
	defer e.mu.Unlock()
	kind, ok := e.kinds[k]
	if !ok {
		return Kind{}, protocol.E(400, "invalid_arguments", "lit-tui cannot edit "+string(k)+" drafts")
	}
	return kind, nil
}

// issueBody edits an existing issue's body.
var issueBody = Kind{
	Read: func(ctx context.Context, s *litclient.Session, d drafts.Draft) (Record, error) {
		got, err := readIssue(ctx, s, d.ProjectID, d.IssueID)
		if err != nil {
			return Record{}, err
		}
		return Record{Exists: true, Title: got.Title, Revision: got.Revision, Content: got.Body, Issue: &got}, nil
	},
	Request: func(d drafts.Draft, content string) protocol.PrepareRequest {
		return litclient.UpdateIssue(d.ProjectID, d.IssueID, d.Revision, litclient.IssueChange{Body: &content})
	},
}

func readIssue(ctx context.Context, s *litclient.Session, project, id string) (protocol.Issue, error) {
	got, err := litclient.Get[protocol.Issue](ctx, s, project, id)
	if err == nil && len(got) != 1 {
		err = protocol.E(500, "invalid_response", "the issue read returned no single issue")
	}
	if err != nil {
		return protocol.Issue{}, err
	}
	return got[0], nil
}

// ExistingFor returns t's existing draft, if there is one: the draft of
// t's record, or for a new record without a draft ID the oldest draft of
// t's kind on its owning issue (an unapplied new comment). A new record
// without an owner has no existing draft to find.
func (e *Editor) ExistingFor(t Target) (drafts.Draft, bool, error) {
	switch {
	case t.Record != "":
		return e.store.Find(t.Project, t.Kind, t.Record)
	case t.Kind.New() && t.Issue != "":
		return e.store.FindOwned(t.Project, t.Kind, t.Issue)
	}
	return drafts.Draft{}, false, nil
}

// Open starts a draft of t. For a claiming kind (drafts.Kind.Claims) it
// claims the owning issue first: another client's claim refuses the edit
// and is named, and nothing is forced. Then it reads the record and records
// a draft holding exactly its content at the read revision. A new record
// is not read: its draft starts empty under a generated draft ID, and new
// comments take no claim. An existing draft is never overwritten: Open
// refuses with draft_exists before claiming, and the caller offers Resume,
// Diff or Discard instead.
func (e *Editor) Open(ctx context.Context, t Target) Started {
	kind, err := e.kind(t.Kind)
	if err != nil {
		return Started{Err: err}
	}
	if _, ok, err := e.ExistingFor(t); err != nil || ok {
		if err == nil {
			err = protocol.E(409, "draft_exists", "this record already has a draft; resume, diff or discard it")
		}
		return Started{Err: err}
	}
	if t.Kind.New() && t.Record == "" {
		t.Record = drafts.NewID()
	}
	r := Started{Kind: drafts.ClaimNone}
	if t.Kind.Claims() {
		if r = e.claim(ctx, t.Issue, t.Title, t.key()); r.Err != nil {
			return r
		}
	}
	d := drafts.Draft{Kind: t.Kind, ProjectID: t.Project, RecordID: t.Record, IssueID: t.Issue, Title: t.Title, Claim: r.Kind}
	var content string
	r.Err = e.g.Do(ctx, func(ctx context.Context, s *litclient.Session) error {
		d.ServiceID = s.Meta.ServiceID
		if t.Kind.New() {
			return nil
		}
		rec, err := kind.Read(ctx, s, d)
		if err == nil && !rec.Exists {
			err = protocol.E(404, "not_found", "the record no longer exists")
		}
		if rec.Title != "" {
			d.Title = rec.Title
		}
		d.Revision, d.Base, content = rec.Revision, rec.Content, rec.Content
		return err
	})
	if r.Err == nil {
		r.Draft, r.Err = e.store.Create(d, content)
	}
	if r.Err != nil && t.Kind.Claims() {
		e.release(ctx, t.Issue, t.key()) // the edit did not start: give back its claim
	}
	return r
}
